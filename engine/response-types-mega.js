function makeType(domain, intent) {
  const [did, dname, dkeywords] = domain;
  const [iid, iname, ikeywords] = intent;
  const characteristics = [...new Set([...dkeywords, ...ikeywords])];
  return {
    id: `mega-${did}-${iid}`,
    name: `${dname} — ${iname}`,
    keywords: [...characteristics, `${dname.toLowerCase()} ${iname.toLowerCase()}`],
    characteristics,
    unit: iid === 'percentage' ? '%' : '',
    domain: did,
    intent: iid,
    searchProfile: characteristics
  };
}

export const MEGA_RESPONSE_TYPES = DOMAINS.flatMap(domain => INTENTS.map(intent => makeType(domain, intent)));
if (MEGA_RESPONSE_TYPES.length !== 10000) {
  throw new Error(`Expected 10000 mega response types, got ${MEGA_RESPONSE_TYPES.length}`);
}

